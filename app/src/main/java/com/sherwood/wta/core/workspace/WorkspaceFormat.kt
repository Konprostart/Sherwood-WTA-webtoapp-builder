package com.sherwood.wta.core.workspace

import com.google.gson.annotations.SerializedName
import com.sherwood.wta.core.agent.session.AgentMessage
import com.sherwood.wta.core.agent.session.SessionConfig

/**
 * The portable description of one workspace: `.sherwoodworkspace` is a plain zip whose
 *
 * ```
 *   workspace.json   this document (session metadata, config, full message history)
 *   files/…          the session's project files, filtered by WorkspaceAllowlist
 *   manifest.json    size + sha256 of every entry, written LAST
 * ```
 *
 * The conversation travels *inside* `workspace.json` rather than as the session store's
 * own `.session/messages.json`: importing must be able to build a session whose id it
 * chooses, and re-using the store's private file would tie a transfer format to an
 * internal layout that has already changed once.
 *
 * [SerializedName] names are pinned because they are the on-disk contract between two
 * installs that need not be running the same build.
 */
internal data class WorkspaceDocument(
    @SerializedName("format") val format: String = WorkspaceBundle.FORMAT,
    @SerializedName("bundleVersion") val bundleVersion: Int = WorkspaceBundle.VERSION,
    @SerializedName("exportedAt") val exportedAt: Long = 0L,
    @SerializedName("exportedBy") val exportedBy: WorkspaceOrigin = WorkspaceOrigin(),
    @SerializedName("session") val session: WorkspaceSession = WorkspaceSession()
)

/** Provenance, so an import can explain "written by a build older than this one". */
internal data class WorkspaceOrigin(
    @SerializedName("app") val app: String = WorkspaceBundle.PRODUCT,
    @SerializedName("versionName") val versionName: String = "",
    @SerializedName("versionCode") val versionCode: Int = 0
)

internal data class WorkspaceSession(
    @SerializedName("title") val title: String = "",
    @SerializedName("titleAutoGenerated") val titleAutoGenerated: Boolean = true,
    @SerializedName("pinned") val pinned: Boolean = false,
    @SerializedName("createdAt") val createdAt: Long = 0L,
    @SerializedName("updatedAt") val updatedAt: Long = 0L,
    @SerializedName("planSlugs") val planSlugs: List<String> = emptyList(),
    @SerializedName("config") val config: SessionConfig = SessionConfig(),
    @SerializedName("messages") val messages: List<AgentMessage> = emptyList()
)

/**
 * Session configuration reduced to what is meaningful on a different device.
 *
 * Three fields are dropped on purpose, and each would be a real defect if kept:
 *
 *  - `contextAppIds` are **row ids** of the exporting device's database. On the
 *    importing device the same numbers address *different* apps, so carrying them
 *    would feed the assistant context from an unrelated project.
 *  - `builtApks` hold **absolute host paths** to artifacts that are not in the bundle.
 *  - nothing else is dropped: model ids, temperature, turn budget and the user's
 *    custom rules describe the conversation and travel with it.
 *
 * Everything is re-normalised on import as well ([sanitize]), because Gson bypasses
 * Kotlin constructor defaults and a hostile or hand-edited document can omit a field
 * that the model declares non-null.
 */
internal fun SessionConfig.forTransfer(): SessionConfig = copy(
    contextAppIds = emptyList(),
    builtApks = emptyList()
)

/** Null-safe rebuild of anything a hand-edited document could have left null. */
@Suppress("USELESS_CAST")
internal fun SessionConfig.sanitize(): SessionConfig = SessionConfig(
    textModelId = textModelId,
    imageModelId = imageModelId,
    temperature = if (temperature.isFinite()) temperature else 0.7f,
    maxTurns = if (maxTurns > 0) maxTurns else 24,
    customRules = (customRules as? List<String>)?.filter { it.isNotBlank() } ?: emptyList(),
    contextAppIds = emptyList(),
    contextModuleIds = contextModuleIdsSafe,
    builtApks = emptyList()
)

/**
 * Typed failures. Each one is something the user can act on, which is why they are not
 * collapsed into a single "invalid workspace file".
 */
internal sealed class WorkspaceBundleException(message: String) : Exception(message) {

    /** The archive has no `workspace.json` — not a workspace bundle at all. */
    class MissingDocument : WorkspaceBundleException("workspace.json is missing from the bundle")

    /** `workspace.json` is present but is not a document this build can read. */
    class MalformedDocument : WorkspaceBundleException("workspace.json is not a valid workspace document")

    /** `format` is not ours (e.g. a `.zip` of something else picked by mistake). */
    class UnsupportedFormat(found: String) :
        WorkspaceBundleException("Bundle format '$found' is not a Sherwood workspace")

    /** Written by a newer build than this one understands. */
    class UnsupportedVersion(found: Int) :
        WorkspaceBundleException("Bundle version $found is newer than this build supports")

    /**
     * The archive carries a path the allowlist refuses. Refusing the whole import (as
     * opposed to skipping the entry) is deliberate: a bundle that contains a private
     * key is not a bundle whose remaining contents should be trusted into a sandbox.
     */
    class ForbiddenEntry(path: String, reason: WorkspaceAllowlist.Refusal) :
        WorkspaceBundleException("Bundle entry '$path' is not allowed ($reason)")

    /** Structural budget exceeded (entry count / extracted bytes). */
    class TooLarge(detail: String) : WorkspaceBundleException(detail)

    /** Session the caller asked to export does not exist. */
    class NoSuchSession(sessionId: String) :
        WorkspaceBundleException("No session $sessionId to export")

    /** Nothing is open, so "export the current workspace" has no subject. */
    class NoCurrentSession :
        WorkspaceBundleException("No agent session is open to export")
}
